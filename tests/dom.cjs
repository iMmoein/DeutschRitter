const {JSDOM,VirtualConsole} = require('jsdom');
const {readFileSync} = require('node:fs');
const assert = require('node:assert/strict');
let html = readFileSync('index.html','utf8');
html = html.replace(/<script src="([^"]+)"><\/script>/g,(_,path)=>`<script>${readFileSync(path,'utf8')}</script>`);
const errors=[];
const vc = new VirtualConsole();
vc.on('jsdomError',error=>errors.push(error.message));
(async()=>{
 const dom=new JSDOM(html,{url:'http://localhost:8000/',runScripts:'dangerously',virtualConsole:vc});
 await new Promise(resolve=>dom.window.addEventListener('load',resolve,{once:true}));
 const w=dom.window, d=w.document;
 assert(d.getElementById('main-view-container').textContent.includes('مدیریت پیشرفت'));
 w.eval('gameState.currentActId="act1";gameState.activeTab="quest";gameState.currentQuestStep="learning";renderActiveView()');
 assert(d.getElementById('learning-answer-0'));
 d.getElementById('learning-answer-0').value='heiße';
 w.submitLearningExercise('act1',0);
 assert(d.getElementById('learning-feedback-0').textContent.includes('پاسخ هدف درست'));
 w.submitLearningExercise('act1',0);
 assert.equal(w.eval('gameState.learningEvidence.length'),1);
 d.getElementById('learning-writing').value='Ich heiße Sara. Ich wohne in Berlin.';
 w.saveLearningDraft('act1');
 assert(JSON.parse(w.localStorage.getItem('deutsch_ritter_v3_save')).learningDrafts.act1.includes('Sara'));
 w.eval('gameState.learningDrafts={};loadSave();gameState.activeTab="quest";gameState.currentQuestStep="learning";renderActiveView()');
 assert(d.getElementById('learning-writing').value.includes('Sara'));
 w.eval('gameState.activeTab="srs";renderActiveView()');
 assert(d.querySelector('.flashcard-wrap'));
 w.revealSrsCard();
 w.rateSrsCard('good');
 w.eval('gameState.activeTab="test";gameState.placement={currentQIdx:39,score:0,active:true};renderActiveView()');
 assert(d.getElementById('main-view-container').textContent.includes('40'));
 w.submitPlacementAnswer(0);
 assert(!d.getElementById('main-view-container').innerHTML.includes('onclick="submitPlacementAnswer'));
 assert.deepEqual(errors,[]);
 dom.window.close();
 console.log('PASS: DOM startup, learning workshop, duplicate attempt, draft save/reload, SRS rating and final placement question.');
})().catch(error=>{console.error(error);process.exitCode=1;});
